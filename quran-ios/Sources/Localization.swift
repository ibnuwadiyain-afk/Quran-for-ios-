enum AppLanguage: String, CaseIterable {
    case system = "system"
    case english = "en"
    case arabic = "ar"
    case indonesian = "id"
    case turkish = "tr"
    case urdu = "ur"
    case french = "fr"
    case russian = "ru"
    case spanish = "es"
    case bengali = "bn"

    var resolvedCode: String {
        if self != .system { return rawValue }
        let preferred = Locale.preferredLanguages.first?.lowercased() ?? "en"
        for lang in AppLanguage.allCases where lang != .system {
            if preferred.hasPrefix(lang.rawValue) {
                return lang.rawValue
            }
        }
        return "en"
    }

    var isRTL: Bool {
        let code = resolvedCode
        return code == "ar" || code == "ur"
    }

    var displayName: String {
        switch self {
        case .system: return L10n.tr("lang.system")
        case .english: return "English"
        case .arabic: return "العربية (Arabic)"
        case .indonesian: return "Bahasa Indonesia"
        case .turkish: return "Türkçe (Turkish)"
        case .urdu: return "اردو (Urdu)"
        case .french: return "Français (French)"
        case .russian: return "Русский (Russian)"
        case .spanish: return "Español (Spanish)"
        case .bengali: return "বাংলা (Bengali)"
        }
    }
}

enum L10n {
    static var currentLanguage: AppLanguage {
        AppSettings.language
    }

    static var isRTL: Bool {
        currentLanguage.isRTL
    }

    static func applyLayoutDirection(to window: UIWindow?) {
        let attribute: UISemanticContentAttribute = isRTL ? .forceRightToLeft : .forceLeftToRight
        UIView.appearance().semanticContentAttribute = attribute
        UINavigationBar.appearance().semanticContentAttribute = attribute
        UITabBar.appearance().semanticContentAttribute = attribute
        UITableView.appearance().semanticContentAttribute = attribute
        window?.semanticContentAttribute = attribute
    }

    static func tr(_ key: String) -> String {
        let lang = currentLanguage.resolvedCode
        if let table = translations[lang], let value = table[key] {
            return value
        }
        return translations["en"]?[key] ?? key
    }

    static func format(_ key: String, _ args: CVarArg...) -> String {
        let template = tr(key)
        return String(format: template, arguments: args)
    }

